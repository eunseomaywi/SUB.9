function updateLanguageToggle(){
  document.querySelectorAll(".lang-toggle").forEach(btn=>{
    btn.innerHTML = `<span class="${lang === "ko" ? "active" : ""}">KR</span> <span>/</span> <span class="${lang === "en" ? "active" : ""}">EN</span>`;
    btn.setAttribute("aria-pressed", lang === "en" ? "true" : "false");
    btn.setAttribute("aria-label", lang === "ko" ? "Switch language to English" : "한국어로 언어 변경");
  });
}

function applyLanguage(){
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key=el.dataset.i18n;
    if(translations[lang][key]) el.innerHTML=translations[lang][key];
  });
  updateLanguageToggle();
  renderTier(currentTier);
}

function openMenu(){
  const overlay = document.querySelector(".menu-overlay");
  const toggle = document.querySelector(".menu-toggle");
  if(!overlay || !toggle) return;
  lastFocusedElement = document.activeElement;
  overlay.classList.add("open");
  overlay.setAttribute("aria-hidden","false");
  toggle.setAttribute("aria-expanded","true");
  document.body.classList.add("menu-open");
  overlay.querySelector(".menu-close")?.focus();
}

function closeMenu(){
  const overlay = document.querySelector(".menu-overlay");
  const toggle = document.querySelector(".menu-toggle");
  if(!overlay || !toggle) return;
  overlay.classList.remove("open");
  overlay.setAttribute("aria-hidden","true");
  toggle.setAttribute("aria-expanded","false");
  document.body.classList.remove("menu-open");
  if(lastFocusedElement instanceof HTMLElement) lastFocusedElement.focus();
}

function trapMenuFocus(event){
  const overlay = document.querySelector(".menu-overlay.open");
  if(!overlay || event.key !== "Tab") return;
  const focusable = [...overlay.querySelectorAll("a,button")].filter(el=>!el.disabled);
  if(!focusable.length) return;
  const first = focusable[0];
  const last = focusable[focusable.length - 1];
  if(event.shiftKey && document.activeElement === first){
    event.preventDefault();
    last.focus();
  }else if(!event.shiftKey && document.activeElement === last){
    event.preventDefault();
    first.focus();
  }
}

function initSharedShell(){
  renderSiteShell();
  document.querySelectorAll(".lang-toggle").forEach(btn=>btn.addEventListener("click",()=>{
    lang=lang==="ko"?"en":"ko";
    localStorage.setItem("sub9-lang",lang);
    applyLanguage();
  }));
  document.querySelectorAll(".menu-toggle").forEach(btn=>btn.addEventListener("click",openMenu));
  document.querySelectorAll(".menu-close,.menu-links a").forEach(el=>el.addEventListener("click",closeMenu));
  document.addEventListener("keydown",event=>{
    if(event.key==="Escape") closeMenu();
    trapMenuFocus(event);
  });
  document.getElementById("currentYear")?.append(new Date().getFullYear());
}

